  // ====================================
  // 2) Helpers: get/set text & attributes
  // ====================================
  function getByPath(root, path) {
    return path.split('.').reduce((acc, k) => (acc && acc[k] != null ? acc[k] : undefined), root);
  }

  function setNodeText(node, value) {
    // Return early if the node is an input/textarea, as their text is handled by placeholders.
    if (node.tagName === 'INPUT' || node.tagName === 'TEXTAREA') {
      return;
    }

    // This part handles text for all other elements like <p>, <span>, <h1>, etc.
    if (node.firstElementChild == null) {
      node.textContent = value;
    } else {
      const hasDirectText = Array.from(node.childNodes)
        .some(n => n.nodeType === Node.TEXT_NODE && n.textContent.trim().length > 0);
      if (hasDirectText) {
        node.childNodes.forEach(n => { if (n.nodeType === Node.TEXT_NODE) n.textContent = value; });
      } else {
        node.setAttribute('data-i18n-text', value);
      }
    }
  }

  function setCommonAttributes(node, value) {
    // single key applies to common attributes too
    if (node.hasAttribute('placeholder') || node.tagName === 'INPUT' || node.tagName === 'TEXTAREA') {
      node.setAttribute('placeholder', value);
    }
    if (node.hasAttribute('title')) {
      node.setAttribute('title', value);
    }
    if (node.hasAttribute('alt')) {
      node.setAttribute('alt', value);
    }
    if (node.hasAttribute('aria-label')) {
      node.setAttribute('aria-label', value);
    }
    // الإضافة الجديدة والمهمة لترجمة عنوان مجموعة الخيارات
    if (node.tagName === 'OPTGROUP' && node.hasAttribute('label')) {
      node.setAttribute('label', value);
    }
  }

  // ====================================
  // 3) Direction + UI helpers
  // ====================================
  function applyDirection(lang) {
    const isAR = lang === 'ar';
    const html = document.documentElement;
    const body = document.body;
    const app = document.getElementById('app');

    html.setAttribute('lang', lang);
    html.setAttribute('dir', isAR ? 'rtl' : 'ltr');
    if (body) body.setAttribute('dir', isAR ? 'rtl' : 'ltr');

    html.classList.toggle('rtl', isAR);
    html.classList.toggle('ltr', !isAR);
    if (body) {
      body.classList.toggle('rtl', isAR);
      body.classList.toggle('ltr', !isAR);
    }
    if (app) {
      app.classList.toggle('rtl', isAR);
      app.classList.toggle('ltr', !isAR);
    }
  }

  function setActiveLanguageButton(lang) {
    const btns = document.querySelectorAll('.language-option');
    btns.forEach(btn => {
      const isActive = btn.dataset.lang === lang;
      btn.classList.toggle('active', isActive);
      btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });
  }

  // ====================================
  // 4) Core translation application
  // ====================================
  function translateElement(el, lang) {
    const translations = dict[lang] || {};
    const key = el.getAttribute('data-i18n-key');
    if (!key) return;

    const val = getByPath(translations, key);
    if (typeof val === 'string') {
      setNodeText(el, val);
      setCommonAttributes(el, val);
    } else if (val && typeof val === 'object') {
      const prefer = val.title || val.label || val.text || null;
      if (prefer) {
        setNodeText(el, prefer);
        setCommonAttributes(el, prefer);
      } else {
        // complex object without title/label/text — ignore gracefully
      }
    } else {
      // missing key — fail silently (or console.warn if you prefer)
      // console.warn('[i18n] Missing key:', lang, key);
    }
  }

  function applyTranslations(lang) {
    const all = document.querySelectorAll('[data-i18n-key]');
    all.forEach(el => translateElement(el, lang));

    // head <title> support
    const titleEl = document.querySelector('head title[data-i18n-key]');
    if (titleEl) {
      const v = getByPath(dict[lang] || {}, titleEl.getAttribute('data-i18n-key'));
      if (typeof v === 'string') titleEl.textContent = v;
    }

    applyDirection(lang);
    setActiveLanguageButton(lang);
  }

  // ====================================
  // 5) Public API
  // ====================================
  function updateLanguage(lang) {
    // 1. احصل على اللغة الحالية المحفوظة
    const currentLang = localStorage.getItem('preferred_language');

    // 2. قارن اللغة الجديدة باللغة الحالية
    if (currentLang !== lang) {
      // 3. فقط إذا كانت اللغة مختلفة، قم بحفظها وإعادة التحميل
      try {
        localStorage.setItem('preferred_language', lang);
        window.location.reload();
      } catch (_) {
        console.warn('[i18n] Could not save language or reload.');
      }
    } else {
      // إذا كانت اللغة هي نفسها، فقط قم بتطبيق الترجمات دون إعادة تحميل
      applyTranslations(lang);
    }
  }

  window.updateLanguage = updateLanguage;
  window.t = function (key, lang) {
    const _lang = lang || localStorage.getItem('preferred_language') || document.documentElement.lang || 'ar';
    return getByPath(dict[_lang] || {}, key) || key;
  };

  // ====================================
  // 6) Dynamic translation (MutationObserver)
  // ====================================
  let observer;
  function ensureObserver(lang) {
    if (observer) return;
    observer = new MutationObserver(mutations => {
      mutations.forEach(m => {
        // translate any newly added nodes with data-i18n-key
        m.addedNodes && m.addedNodes.forEach(node => {
          if (node.nodeType !== 1) return; // element only
          if (node.hasAttribute && node.hasAttribute('data-i18n-key')) {
            translateElement(node, lang);
          }
          const descendants = node.querySelectorAll ? node.querySelectorAll('[data-i18n-key]') : [];
          descendants.forEach(el => translateElement(el, lang));
        });
      });
    });
    observer.observe(document.body, { childList: true, subtree: true });
  }

  // ====================================
  // 7) Boot
  // ====================================
  document.addEventListener('DOMContentLoaded', function () {
    const lang = localStorage.getItem('preferred_language') || document.documentElement.lang || 'ar';
    applyTranslations(lang);
    ensureObserver(lang);

    // keep buttons wired to updateLanguage if not already
    document.addEventListener('click', function (e) {
      const btn = e.target.closest('.language-option');
      if (btn && btn.dataset && btn.dataset.lang) {
        updateLanguage(btn.dataset.lang);
      }
    });
  });


